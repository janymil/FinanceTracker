#!/usr/bin/env node
/**
 * Generates public/sitemap.xml for the three supported languages.
 *
 * Run after any change to public routes:  npm run sitemap:generate
 *
 * Rules baked in on purpose:
 *  - only public pages, never signed-in screens;
 *  - every page is listed once per language, with hreflang alternates so Google
 *    serves the visitor's language instead of guessing;
 *  - slugs avoid wording that suggests a licensed financial service.
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const BASE = 'https://kaptia.app';
const LANGUAGES = ['sk', 'en', 'es'];
const DEFAULT_LANGUAGE = 'en';

// path ('' = home), change frequency, priority
const PAGES = [
  ['', 'weekly', '1.0'],
  ['/features', 'monthly', '0.9'],
  ['/pricing', 'monthly', '0.9'],
  ['/help', 'monthly', '0.7'],
  ['/contact', 'yearly', '0.6'],
  ['/privacy-policy', 'yearly', '0.3'],
  ['/terms-of-service', 'yearly', '0.3'],
  ['/cookie-policy', 'yearly', '0.2'],
  ['/reclamaciones', 'yearly', '0.3'],
];

const today = new Date().toISOString().slice(0, 10);

function urlFor(lang, path) {
  return `${BASE}/${lang}${path}`;
}

function alternates(path) {
  return LANGUAGES.map(
    (lang) => `    <xhtml:link rel="alternate" hreflang="${lang}" href="${urlFor(lang, path)}"/>`
  )
    .concat(`    <xhtml:link rel="alternate" hreflang="x-default" href="${urlFor(DEFAULT_LANGUAGE, path)}"/>`)
    .join('\n');
}

const entries = [];
for (const [path, changefreq, priority] of PAGES) {
  for (const lang of LANGUAGES) {
    entries.push(
      `  <url>\n` +
        `    <loc>${urlFor(lang, path)}</loc>\n` +
        `    <lastmod>${today}</lastmod>\n` +
        `    <changefreq>${changefreq}</changefreq>\n` +
        `    <priority>${priority}</priority>\n` +
        `${alternates(path)}\n` +
        `  </url>`
    );
  }
}

const xml =
  `<?xml version="1.0" encoding="UTF-8"?>\n` +
  `<!-- Generated by scripts/generate-sitemap.mjs — do not edit by hand. -->\n` +
  `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n` +
  `        xmlns:xhtml="http://www.w3.org/1999/xhtml">\n` +
  `${entries.join('\n')}\n` +
  `</urlset>\n`;

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
writeFileSync(resolve(root, 'public/sitemap.xml'), xml, 'utf8');
console.log(`[sitemap] wrote ${PAGES.length * LANGUAGES.length} URLs to public/sitemap.xml`);
