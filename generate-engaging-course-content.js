import OpenAI from 'openai';
import dotenv from 'dotenv';
import fs from 'fs';

dotenv.config({ path: '.env.local' });

const openai = new OpenAI({
  apiKey: process.env.OPENAI_API_KEY,
});

async function generateEngagingCourseContent() {
  console.log('🚀 Generating high-quality, engaging financial literacy course content using GPT-4o...');

  try {
    const response = await openai.chat.completions.create({
      model: "gpt-4o", // the newest OpenAI model is "gpt-4o" which was released May 13, 2024. do not change this unless explicitly requested by the user
      messages: [
        {
          role: "system",
          content: `You are an expert educational content designer specializing in gamified financial literacy. Create engaging, interactive, and comprehensive course content that follows modern edtech principles like Duolingo, Memrise, and Kahoot.

CRITICAL REQUIREMENTS:
- Content must be engaging, practical, and immediately actionable
- Use storytelling, real-world scenarios, and relatable examples
- Include interactive elements, thought-provoking questions, and practical tips
- Each section should build knowledge progressively
- Content should be comprehensive but digestible in 5-minute chunks
- Focus on practical application, not theoretical concepts
- Use modern, conversational language that connects with users

Generate JSON-structured content for a comprehensive "Budgeting Basics" course with three progressive levels.`
        },
        {
          role: "user",
          content: `Create a comprehensive "Budgeting Basics" course with 3 levels:

LEVEL 1: "Foundation - Understanding Your Money Flow"
- Income Tracking tab: How to identify and track all income sources
- Expense Categories tab: Understanding different types of expenses
- Cash Flow Basics tab: Simple cash flow analysis

LEVEL 2: "Building Your First Budget" 
- Budget Planning tab: Step-by-step budget creation
- The 50/30/20 Rule tab: Popular budgeting framework
- Budget Tools tab: Methods and tools for budgeting

LEVEL 3: "Advanced Budget Management"
- Budget Optimization tab: Fine-tuning your budget
- Emergency Planning tab: Building financial cushions
- Budget Review tab: Regular budget maintenance

For each tab, create diverse content blocks:
- 'text': Core educational content (engaging, story-driven)
- 'example': Real-world scenarios with specific numbers
- 'tip': Actionable advice users can implement immediately
- 'warning': Common mistakes to avoid
- 'scenario': Interactive scenarios for user thinking
- 'interactive': Action items or reflection questions

Each level should have:
- Clear learning objectives (3-5 specific goals)
- Progressive difficulty
- Practical exercises in the exercises array

Return ONLY valid JSON with this exact structure:
{
  "id": "budgeting-basics",
  "title": "Budgeting Basics",
  "description": "Master the fundamentals of personal budgeting",
  "icon": "Calculator",
  "levels": [
    {
      "id": "level-1",
      "title": "Foundation - Understanding Your Money Flow",
      "description": "Learn to track and categorize your financial flow",
      "difficulty": "Beginner",
      "estimatedTime": "5 minutes",
      "xpReward": 50,
      "learningObjectives": ["objective1", "objective2", "objective3"],
      "tabs": [
        {
          "id": "income-tracking",
          "title": "Income Tracking",
          "icon": "💰",
          "content": [
            {
              "type": "text",
              "title": "Title",
              "content": "Content here"
            }
          ]
        }
      ],
      "exercises": [
        {
          "id": "ex1",
          "type": "multiple-choice",
          "question": "Question here",
          "options": ["A", "B", "C", "D"],
          "correctAnswer": "A",
          "explanation": "Explanation",
          "points": 10
        }
      ]
    }
  ]
}

Make the content engaging, practical, and comprehensive. Focus on real-world application and user engagement.`
        }
      ],
      response_format: { type: "json_object" }
    });

    const courseContent = JSON.parse(response.choices[0].message.content);
    
    // Write to courseContent.ts file
    const courseContentFile = `// High-quality, engaging financial literacy course content generated by GPT-4o
// This content follows modern edtech principles and gamification best practices

export const COURSE_CONTENT = ${JSON.stringify(courseContent, null, 2)};

export default COURSE_CONTENT;
`;

    fs.writeFileSync('client/src/data/courseContent.ts', courseContentFile);
    
    console.log('✅ Successfully generated engaging course content!');
    console.log('📁 Content saved to: client/src/data/courseContent.ts');
    console.log(`📊 Generated: ${courseContent.levels?.length || 0} levels with comprehensive educational content`);
    
    return courseContent;

  } catch (error) {
    console.error('❌ Error generating course content:', error);
    process.exit(1);
  }
}

// Run the content generation
generateEngagingCourseContent();